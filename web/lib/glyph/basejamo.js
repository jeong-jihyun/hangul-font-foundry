// 선분 → 두께 t 의 네모 (끝을 t/2 만큼 늘려 모서리가 잘 이어지게)
function bar(x1, y1, x2, y2, t) {
  const dx = x2 - x1, dy = y2 - y1, l = Math.hypot(dx, dy) || 1;
  const ux = dx / l, uy = dy / l, nx = -uy * t / 2, ny = ux * t / 2, e = t / 2;
  const a = [x1 - ux * e, y1 - uy * e], b = [x2 + ux * e, y2 + uy * e];
  const p = [[a[0] + nx, a[1] + ny], [b[0] + nx, b[1] + ny], [b[0] - nx, b[1] - ny], [a[0] - nx, a[1] - ny]];
  return { start: p[0], closed: true, segs: p.slice(1).concat([p[0]]).map((q) => ["L", q[0], q[1]]) };
}

// 뼈대 목록을 상자(x1,y1,x2,y2)에 그려 하위 경로들로
function draw(items, box, t) {
  const [x1, y1, x2, y2] = box, w = x2 - x1, h = y2 - y1;
  const X = (u) => x1 + u * w, Y = (v) => y1 + v * h;
  const out = [];
  for (const it of items) {
    if (Array.isArray(it)) out.push(bar(X(it[0]), Y(it[1]), X(it[2]), Y(it[3]), t));
    else {
      const [cx, cy, rx, ry] = it.o;
      const RX = rx * w, RY = ry * h;
      out.push(ellipseSub(X(cx), Y(cy), RX + t / 2, RY + t / 2));
      out.push(ellipseSub(X(cx), Y(cy), Math.max(4, RX - t / 2), Math.max(4, RY - t / 2)));
    }
  }
  return out;
}

const inset = ([x1, y1, x2, y2], k) => { const dx = (x2 - x1) * k, dy = (y2 - y1) * k; return [x1 + dx, y1 + dy, x2 - dx, y2 - dy]; };

function consonant(ch, box, t) {
  const b = inset(box, 0.1);
  if (PAIR[ch]) {
    const [a, c] = [...PAIR[ch]], mid = (b[0] + b[2]) / 2, gap = (b[2] - b[0]) * 0.04;
    const t2 = t * 0.85;
    return [...draw(C[a], [b[0], b[1], mid - gap, b[3]], t2), ...draw(C[c], [mid + gap, b[1], b[2], b[3]], t2)];
  }
  return draw(C[ch], b, t);
}

function vowel(v, box, t) {
  const vt = VT[v];
  const b = vt === "V" ? inset(box, 0.04) : inset(box, 0.05);
  return draw((vt === "V" ? VV : vt === "H" ? HV : MV)[v], b, t);
}

// 무게(굵기) 기본 = 보통 고딕
export function baseJamo({ weight = 60 } = {}) {
  const out = {};
  const p2 = (n) => String(n).padStart(2, "0");
  const put = (key, subs) => { out[key] = subsToD(orient(subs)); };
  [...L].forEach((l, i) => {
    for (const vt of "VHM") for (const b of [0, 1]) put(`L${p2(i)}${vt}${b}`, consonant(l, ZONES[vt + b].L, weight));
  });
  [...V].forEach((v, i) => {
    for (const b of [0, 1]) put(`V${p2(i)}${b}`, vowel(v, ZONES[VT[v] + b].V, weight));
  });
  [...T].forEach((tch, i) => {
    for (const vt of "VHM") put(`T${p2(i)}${vt}`, consonant(tch, ZONES[vt + "1"].T, weight * 0.95));
  });
  return out;
}
